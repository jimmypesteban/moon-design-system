// Mosaic logo assets — original vector artwork, generated for this design
// system. Pass these into the `Logo` component's `src`/`markSrc` props
// rather than hardcoding a path — bundlers (Next.js, Vite) resolve these
// imports to a real, hashed asset URL at build time, the same as importing
// an image from an app's own /public folder.
//
// All 11 brand colors are available: red (default), white, black, yellow,
// orange, pink, purple, green, forest, blue, ocean — each as a full
// wordmark (`mosaicLogo*`) and a mark-only tile (`mosaicMark*`). Everything
// is SVG, so the `*Svg` names — kept for the download tooling, which offers
// "the vector original" separately from the rendered asset — point at the
// same files as their unsuffixed twins.

